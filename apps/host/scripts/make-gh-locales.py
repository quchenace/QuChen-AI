NBSP = "\u00a0"


def french(text):
    """The same French spacing as scripts/fr_sync.py: a typographic apostrophe, a no-break space before : ; ? ! % and inside the guillemets."""
    text = re.sub(r"(?<=[A-Za-z\u00c0-\u017f])'(?=[A-Za-z\u00c0-\u017f{])", "\u2019", text)
    text = re.sub(r"(?<=\S) ([:;?!])", NBSP + r"\1", text)
    text = re.sub(r"(?<=[\d}]) %", NBSP + "%", text)
    return text


def write(lang, values):
    assert len(values) == len(EN), (lang, len(values), len(EN))
    for source, text in zip(EN, values):
        assert sorted(re.findall(r"\{\d+\}", source)) == sorted(re.findall(r"\{\d+\}", text)), (lang, source, text)
    if lang == "fr":
        values = [french(v) for v in values]
    data = {f"gh{i + 1:02d}": text for i, text in enumerate(values)}
    (here / f"gh-{lang}.json").write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


